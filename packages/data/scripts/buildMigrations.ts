/**
 * Regenerates the schema's SQL and compiles it into the module the runner
 * applies.
 *
 * Drizzle describes the schema, but it is not in the app's bundle and its
 * output is `.sql` on disk, which Metro does not resolve. So the statements
 * are compiled into a TypeScript module once, at the point the schema changes,
 * and committed. Nothing reads a file at runtime and nothing parses SQL on a
 * device.
 *
 *     pnpm --dir packages/data db:generate --name=the_ledger
 *
 * Arguments are passed through to `drizzle-kit generate`; naming the migration
 * keeps the file names describing what they do rather than the two random
 * words drizzle picks. `buildMigrations.test.ts` fails if the committed module
 * and the committed SQL have come apart.
 */
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PACKAGE_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SQL_DIR = join(PACKAGE_ROOT, 'drizzle');
const OUTPUT = join(PACKAGE_ROOT, 'src/migrations/generated.ts');

/** What drizzle-kit puts between two statements. */
const BREAKPOINT = '--> statement-breakpoint';

interface GeneratedMigration {
  id: number;
  name: string;
  statements: string[];
}

/**
 * Reads the generated SQL in the order drizzle numbered it.
 *
 * The file name carries both the position and the name — `0003_the_ledger.sql`
 * — so the journal is not needed to order them, and a file that does not match
 * is a mistake rather than something to skip quietly.
 */
export function readGeneratedMigrations(directory = SQL_DIR): GeneratedMigration[] {
  const files = readdirSync(directory)
    .filter((file) => file.endsWith('.sql'))
    .sort();

  return files.map((file) => {
    const match = /^(\d{4})_(.+)\.sql$/.exec(file);
    if (match === null) {
      throw new Error(`Unexpected file in ${directory}: ${file}`);
    }

    const [, index, name] = match;
    const statements = readFileSync(join(directory, file), 'utf8')
      .split(BREAKPOINT)
      .map((statement) => statement.trim())
      .filter((statement) => statement.length > 0);

    if (statements.length === 0) {
      throw new Error(`${file} has no statements.`);
    }

    // Drizzle numbers from 0; migrations here are numbered from 1 so that 0
    // can mean "never migrated".
    return { id: Number(index) + 1, name, statements };
  });
}

/**
 * Makes a statement safe to sit inside a template literal.
 *
 * A template literal rather than a quoted string so that the SQL keeps the
 * shape it was generated in and stays readable in review. SQLite quotes
 * identifiers with the same backtick, hence the escaping.
 */
function asTemplateLiteral(statement: string): string {
  const escaped = statement
    .replaceAll('\\', '\\\\')
    .replaceAll('`', '\\`')
    .replaceAll('${', '\\${');

  return `\`${escaped}\``;
}

export function renderModule(migrations: readonly GeneratedMigration[]): string {
  const entries = migrations
    .map((migration) => {
      const statements = migration.statements
        .map((statement) => `      ${asTemplateLiteral(statement)},`)
        .join('\n');

      return [
        '  {',
        `    id: ${migration.id},`,
        `    name: '${migration.name}',`,
        '    statements: [',
        statements,
        '    ],',
        '  },',
      ].join('\n');
    })
    .join('\n');

  return [
    '// Generated by scripts/buildMigrations.ts from drizzle/*.sql.',
    '// Run `pnpm --dir packages/data db:generate` instead of editing this file.',
    "import type { Migration } from './types';",
    '',
    'export const GENERATED_MIGRATIONS: readonly Migration[] = [',
    entries,
    '];',
    '',
  ].join('\n');
}

function main(): void {
  const drizzleKit = join(PACKAGE_ROOT, 'node_modules/.bin/drizzle-kit');
  execFileSync(drizzleKit, ['generate', ...process.argv.slice(2)], {
    cwd: PACKAGE_ROOT,
    stdio: 'inherit',
  });

  const migrations = readGeneratedMigrations();
  writeFileSync(OUTPUT, renderModule(migrations), 'utf8');

  const statements = migrations.reduce((total, one) => total + one.statements.length, 0);
  console.log(`Wrote ${migrations.length} migration(s), ${statements} statement(s), to ${OUTPUT}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}
